# and operatörü
durum1= True
durum2= False
durum3= True
print(durum1 and durum2) # False
print(durum1 and durum3) # True
# and operatöründe her iki durumun da True olması gerekir. Eğer bir durum False ise sonuç False olur.

# or operatörü
durum1= True
durum2= False
durum3= True
print(durum1 or durum2) # True
print(durum1 or durum3) # True
# or operatöründe en az bir durumun True olması yeterlidir. Eğer iki durum da False ise sonuç False olur.

# not operatörü
durum1= True
durum2= False
print(not durum1) # False
print(not durum2) # True
# not operatöründe durumun tersini döndürür. True ise False, False ise True döndürür.

