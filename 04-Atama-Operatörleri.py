# arttır
sayi = 10
sayi += 1 # sayi = sayi + 1
print("Arttır:", sayi)

# azalt
sayi = 10
sayi -= 1 # sayi = sayi - 1
print("Azalt:", sayi)

# çarp
sayi = 10
sayi *= 2 # sayi = sayi * 2
print("Çarp:", sayi)

# böl
sayi = 10
sayi /= 2 # sayi = sayi / 2
print("Böl:", sayi)

# mod al
sayi = 10
sayi %= 3 # sayi = sayi % 3
print("Mod Al:", sayi)

# üs al
sayi = 2
sayi **= 3 # sayi = sayi ** 3
print("Üs Al:", sayi)
